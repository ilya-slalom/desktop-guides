def scanned_pdf() -> bytes:
    """A page whose visible lettering is raster pixels, with no PDF text."""
    glyphs = {
        "S": ["11111", "10000", "10000", "11111", "00001", "00001", "11111"],
        "C": ["11111", "10000", "10000", "10000", "10000", "10000", "11111"],
        "A": ["01110", "10001", "10001", "11111", "10001", "10001", "10001"],
        "N": ["10001", "11001", "10101", "10011", "10001", "10001", "10001"],
        "O": ["01110", "10001", "10001", "10001", "10001", "10001", "01110"],
        "L": ["10000", "10000", "10000", "10000", "10000", "10000", "11111"],
        "Y": ["10001", "10001", "01010", "00100", "00100", "00100", "00100"],
    }
    label = "SCAN ONLY"
    scale = 6
    width, height = 400, 100
    pixels = bytearray([255] * width * height)
    for letter_index, letter in enumerate(label):
        if letter == " ":
            continue
        for y, row in enumerate(glyphs[letter]):
            for x, cell in enumerate(row):
                if cell == "1":
                    for dy in range(scale):
                        for dx in range(scale):
                            px = 12 + (letter_index * 6 + x) * scale + dx
                            py = 20 + y * scale + dy
                            pixels[py * width + px] = 0
    compressed = zlib.compress(bytes(pixels), 9)
    commands = b"q 400 0 0 100 72 600 cm /Im1 Do Q"
    objects = [
        b"<< /Type /Catalog /Pages 2 0 R >>",
        b"<< /Type /Pages /Count 1 /Kids [3 0 R] >>",
        b"<< /Type /Page /Parent 2 0 R /MediaBox [0 0 612 792] "
        b"/Resources << /XObject << /Im1 4 0 R >> >> /Contents 5 0 R >>",
        (
            f"<< /Type /XObject /Subtype /Image /Width {width} /Height {height} "
            f"/ColorSpace /DeviceGray /BitsPerComponent 8 /Filter /FlateDecode "
            f"/Length {len(compressed)} >>\nstream\n"
        ).encode()
        + compressed
        + b"\nendstream",
        f"<< /Length {len(commands)} >>\nstream\n".encode()
        + commands
        + b"\nendstream",
    ]
    return write_pdf(objects)


PASSWORD_PADDING = bytes.fromhex(
    "28bf4e5e4e758a4164004e56fffa01082e2e00b6d0683e802f0ca9fe6453697a"
)


def pad_password(password: bytes) -> bytes:
    return (password + PASSWORD_PADDING)[:32]


def rc4(key: bytes, data: bytes) -> bytes:
    state = list(range(256))
    j = 0
    for i in range(256):
        j = (j + state[i] + key[i % len(key)]) % 256
        state[i], state[j] = state[j], state[i]
    output = bytearray()
    i = j = 0
    for value in data:
        i = (i + 1) % 256
        j = (j + state[i]) % 256
        state[i], state[j] = state[j], state[i]
        output.append(value ^ state[(state[i] + state[j]) % 256])
    return bytes(output)


def locked_pdf() -> bytes:
    """PDF Standard Security R2 fixture; test user password is 'guide'."""
    owner_key = hashlib.md5(pad_password(b"owner"), usedforsecurity=False).digest()[:5]
    owner_entry = rc4(owner_key, pad_password(b"guide"))
    document_id = hashlib.md5(
        b"desktop-guides-p0-locked", usedforsecurity=False
    ).digest()
    permissions = -4
    file_key = hashlib.md5(
        pad_password(b"guide")
        + owner_entry
        + struct.pack("<i", permissions)
        + document_id,
        usedforsecurity=False,
    ).digest()[:5]
    user_entry = rc4(file_key, PASSWORD_PADDING)
    commands = b"BT /F1 20 Tf 72 720 Td (Locked guide secret page) Tj ET"
    stream_key = hashlib.md5(
        file_key + bytes([5, 0, 0, 0, 0]), usedforsecurity=False
    ).digest()[:10]
    encrypted = rc4(stream_key, commands)
    objects = [
        b"<< /Type /Catalog /Pages 2 0 R >>",
        b"<< /Type /Pages /Count 1 /Kids [4 0 R] >>",
        b"<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>",
        b"<< /Type /Page /Parent 2 0 R /MediaBox [0 0 612 792] "
        b"/Resources << /Font << /F1 3 0 R >> >> /Contents 5 0 R >>",
        f"<< /Length {len(encrypted)} >>\nstream\n".encode()
        + encrypted
        + b"\nendstream",
        (
            f"<< /Filter /Standard /V 1 /R 2 /Length 40 /O <{owner_entry.hex()}> "
            f"/U <{user_entry.hex()}> /P {permissions} >>"
        ).encode(),
    ]
    trailer = (
        f" /Encrypt 6 0 R /ID [<{document_id.hex()}> <{document_id.hex()}>]"
    ).encode()
    return write_pdf(objects, trailer)


