def tiny_jpeg(width: int, height: int) -> bytes:
    """A grey baseline JPEG with no library: every block is DC 0, then EOB."""

    def segment(marker: int, data: bytes) -> bytes:
        return bytes([0xFF, marker]) + struct.pack(">H", len(data) + 2) + data

    blocks = ((width + 7) // 8) * ((height + 7) // 8)
    bits = "001010" * blocks
    bits += "1" * (-len(bits) % 8)
    scan = bytearray()
    for index in range(0, len(bits), 8):
        byte = int(bits[index : index + 8], 2)
        scan.append(byte)
        if byte == 0xFF:
            scan.append(0x00)
    return (
        b"\xff\xd8"
        + segment(0xDB, b"\x00" + b"\x01" * 64)
        + segment(0xC0, struct.pack(">BHHB", 8, height, width, 1) + b"\x01\x11\x00")
        + segment(0xC4, b"\x00" + DC_COUNTS + DC_VALUES)
        + segment(0xC4, b"\x10" + AC_COUNTS + AC_VALUES)
        + segment(0xDA, b"\x01\x01\x00\x00\x3f\x00")
        + bytes(scan)
        + b"\xff\xd9"
    )


def big_map_png(width: int, height: int) -> bytes:
    """A large RGB map drawn from a few precomputed rows, compressed row by row.

    512-pixel cells in six colours by (column + row) % 6, with a dark line
    every 64 pixels, so each zoom level and tile looks different.
    """

    def chunk(kind: bytes, data: bytes) -> bytes:
        return struct.pack(">I", len(data)) + kind + data + struct.pack(
            ">I", zlib.crc32(kind + data) & 0xFFFFFFFF
        )

    colours = [(214, 196, 150), (150, 190, 120), (120, 160, 200), (200, 140, 120), (170, 150, 200), (220, 210, 120)]
    line = bytes((40, 40, 48))
    cells = (width + 511) // 512
    rows: dict[tuple[int, bool], bytes] = {}
    for shift in range(6):
        for dark in (False, True):
            pixels = bytearray()
            for cell in range(cells):
                span = min(512, width - cell * 512)
                colour = line if dark else bytes(colours[(cell + shift) % 6])
                block = bytearray(colour * span)
                if not dark:
                    for x in range(0, span, 64):
                        block[x * 3 : x * 3 + 3] = line
                pixels += block
            rows[(shift, dark)] = b"\x00" + bytes(pixels)
    compressor = zlib.compressobj(1)
    data = bytearray()
    for y in range(height):
        data += compressor.compress(rows[((y // 512) % 6, y % 64 == 0)])
    data += compressor.flush()
    return (
        b"\x89PNG\r\n\x1a\n"
        + chunk(b"IHDR", struct.pack(">IIBBBBB", width, height, 8, 2, 0, 0, 0))
        + chunk(b"IDAT", bytes(data))
        + chunk(b"IEND", b"")
    )


def huge_header_png(width: int, height: int) -> bytes:
    """A header that claims a huge image, with almost no data behind it."""

    def chunk(kind: bytes, data: bytes) -> bytes:
        return struct.pack(">I", len(data)) + kind + data + struct.pack(
            ">I", zlib.crc32(kind + data) & 0xFFFFFFFF
        )

    return (
        b"\x89PNG\r\n\x1a\n"
        + chunk(b"IHDR", struct.pack(">IIBBBBB", width, height, 8, 6, 0, 0, 0))
        + chunk(b"IDAT", zlib.compress(b"\0"))
        + chunk(b"IEND", b"")
    )


def write_pdf(objects: list[bytes], trailer_details: bytes = b"") -> bytes:
    output = bytearray(b"%PDF-1.4\n%\xe2\xe3\xcf\xd3\n")
    offsets = [0]
    for number, body in enumerate(objects, 1):
        offsets.append(len(output))
        output.extend(f"{number} 0 obj\n".encode() + body + b"\nendobj\n")
    xref_offset = len(output)
    output.extend(f"xref\n0 {len(offsets)}\n".encode())
    output.extend(b"0000000000 65535 f \n")
    for offset in offsets[1:]:
        output.extend(f"{offset:010} 00000 n \n".encode())
    output.extend(
        b"trailer\n<< /Size "
        + str(len(offsets)).encode()
        + b" /Root 1 0 R"
        + trailer_details
        + b" >>\n"
        + f"startxref\n{xref_offset}\n%%EOF\n".encode()
    )
    return bytes(output)


def pdf(page_count: int) -> bytes:
    """Small PDF 1.4 writer with text on every page and correct xref offsets."""
    objects: list[bytes] = []
    pages_ref = 2
    font_ref = 3
    kids: list[int] = []
    objects.append(b"<< /Type /Catalog /Pages 2 0 R >>")
    objects.append(b"")  # Page tree, filled after pages are appended.
    objects.append(b"<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>")

    for page_number in range(1, page_count + 1):
        page_ref = len(objects) + 1
        stream_ref = page_ref + 1
        kids.append(page_ref)
        width, height = (612, 792) if page_number % 2 else (792, 612)
        objects.append(
            (
                f"<< /Type /Page /Parent {pages_ref} 0 R "
                f"/MediaBox [0 0 {width} {height}] "
                f"/Resources << /Font << /F1 {font_ref} 0 R >> >> "
                f"/Contents {stream_ref} 0 R >>"
            ).encode()
        )
        text = f"Desktop Guides P0 - page {page_number} of {page_count}"
        commands = f"BT /F1 20 Tf 72 {height - 72} Td ({text}) Tj ET".encode()
        objects.append(
            f"<< /Length {len(commands)} >>\nstream\n".encode()
            + commands
            + b"\nendstream"
        )

    objects[1] = (
        f"<< /Type /Pages /Count {page_count} /Kids ["
        + " ".join(f"{number} 0 R" for number in kids)
        + "] >>"
    ).encode()
    return write_pdf(objects)


